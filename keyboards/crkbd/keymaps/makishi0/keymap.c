// Right half, portrait mode: 5 characters wide, 16 lines tall
static void render_right(void) {
    static uint32_t anim_timer = 0;
    static uint8_t  frame      = 0;

    uint8_t wpm = get_current_wpm();
    if (wpm > 0) {
        oled_on(); // keep the screen awake while typing
    }

    if (timer_elapsed32(anim_timer) < LUNA_FRAME_MS) {
        return;
    }
    anim_timer = timer_read32();
    frame ^= 1;

    oled_clear();
    oled_write_P(PSTR("WPM:"), false);
    oled_set_cursor(0, 1);
    oled_write(get_u8_str(wpm, ' '), false);

    oled_set_cursor(0, 3);
    oled_write_P(PSTR("Layer"), false);
    oled_set_cursor(0, 4);
    switch (get_highest_layer(layer_state)) {
        case _QWERTY:
            oled_write_P(PSTR("Base"), false);
            break;
        case _NUMERIC:
            oled_write_P(PSTR("Num"), false);
            break;
        case _FKEYS:
            oled_write_P(PSTR("Fkeys"), false);
            break;
        case _ADJUST:
            oled_write_P(PSTR("Adj"), false);
            break;
    }

    oled_set_cursor(0, 6);
    oled_write_P(PSTR("OS"), false);
    oled_set_cursor(0, 7);
    switch (detected_host_os()) {
        case OS_MACOS:
        case OS_IOS:
            oled_write_P(PSTR("Mac"), false);
            break;
        case OS_WINDOWS:
            oled_write_P(PSTR("Win"), false);
            break;
        case OS_LINUX:
            oled_write_P(PSTR("Linux"), false);
            break;
        default:
            oled_write_P(PSTR("..."), false);
            break;
    }

    render_luna(frame, wpm);
}

oled_rotation_t oled_init_user(oled_rotation_t rotation) {
    return is_keyboard_master() ? rotation : OLED_ROTATION_270;
}

bool oled_task_user(void) {
    if (!is_keyboard_master()) {
        render_right();
        return false;
    }
    render_layer();
    render_mods();
    render_locks();
    oled_advance_page(true); // keep the last line blank
    return false;
}

